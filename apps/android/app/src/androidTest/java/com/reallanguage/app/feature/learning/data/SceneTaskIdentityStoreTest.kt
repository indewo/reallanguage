import org.json.JSONObject
import org.junit.Assert.*
import org.junit.Test

/** Real JSON decoder and SQLite; the provider/HTTP responses are explicit contract fixtures, not AI evidence. */
class SceneTaskIdentityStoreTest {
    @Test fun repeatedProviderLabelsReproduceTheOldAtomicChapterFailure() = fixture { context, account, runtime, chapters ->
        val transport = fixtureTransport(account, scoped = false) {}
        assertEquals(SceneTaskGenerationResult.Failed, repository(context, runtime, transport).generateTasks(chapters[0]))
        FormationDatabase(context).use { helper ->
            helper.readableDatabase.rawQuery("select count(*) from scene_response_tasks where account_id=?", arrayOf(account)).use {
                assertTrue(it.moveToFirst()); assertEquals(0, it.getInt(0))
            }
        }
    }

    @Test fun scopedBackendIdentitiesSaveEveryFocusAcrossChaptersAndReopenWithoutRequests() = fixture { context, account, runtime, chapters ->
        // Known output generated by the actual TypeScript GenerateSceneResponse use case.
        assertEquals("scene-e3b9d125c4edb70d28284f9c2733ef022e9b786c4e6cb7afa75a7382dbcb86b4",
            scopedIdentity("scene-identity-contract", "c1", "s1"))
        var requests = 0
        val original = repository(context, runtime, fixtureTransport(account, scoped = true) { requests++ })
        val delivered = chapters.map { chapter ->
            val result = original.generateTasks(chapter)
            assertTrue("Every fixed focus must be saved, not rolled back by another task", result is SceneTaskGenerationResult.Ready)
            (result as SceneTaskGenerationResult.Ready).tasks
        }
        assertEquals(4, requests)
        assertEquals(4, delivered.flatten().map { it.taskId }.toSet().size)
        val reopened = repository(context, runtime, HttpTransport { error("Saved tasks must not generate again") })
        chapters.forEachIndexed { index, chapter ->
            assertEquals(SceneTaskGenerationResult.Ready(delivered[index]), reopened.restoreTasks(chapter))
            assertEquals(SceneTaskGenerationResult.Ready(delivered[index]), reopened.generateTasks(chapter))
            assertEquals(chapter.sentences.map { it.textEn }, delivered[index].map { it.targetSentenceEn })
        }
        FormationDatabase(context).use { helper ->
            helper.readableDatabase.rawQuery("select count(*) from scene_response_tasks where account_id=?", arrayOf(account)).use {
                assertTrue(it.moveToFirst()); assertEquals(4, it.getInt(0))
            }
        }
    }

    @Test fun alreadySavedLegacyTaskKeepsItsIdentityWithoutRegeneration() = fixture { context, account, runtime, chapters ->
        val chapter = chapters[0].copy(sentences = chapters[0].sentences.mapIndexed { index, sentence ->
            sentence.copy(isFocus = index == 0)
        })
        FormationDatabase(context).use { helper ->
            helper.writableDatabase.execSQL("insert into scene_response_tasks values (?, ?, 'legacy-task-1', 's1', 0, 'Existing context', '', ?)",
                arrayOf(account, chapter.chapterId, chapter.sentences[0].textEn))
        }
        val restored = repository(context, runtime, HttpTransport { error("Do not migrate saved tasks through AI") }).generateTasks(chapter)
        assertTrue(restored is SceneTaskGenerationResult.Ready)
        assertEquals("legacy-task-1", (restored as SceneTaskGenerationResult.Ready).tasks.single().taskId)
    }

    private fun fixtureTransport(account: String, scoped: Boolean, onRequest: () -> Unit) = HttpTransport { request ->
        onRequest()
        assertEquals("/api/v1/learning/scene-response-tasks", request.path)
        val input = JSONObject(requireNotNull(request.body))
        val sentenceId = input.getString("focusSentenceId")
        val sentences = input.getJSONArray("chapterSentences")
        val sentence = (0 until sentences.length()).map(sentences::getJSONObject).single { it.getString("sentenceId") == sentenceId }
        HttpResponse(200, JSONObject()
            .put("taskId", if (scoped) scopedIdentity(account, input.getString("chapterId"), sentenceId) else "task-1")
            .put("sentenceId", sentenceId).put("targetSentenceEn", sentence.getString("textEn"))
            .put("backgroundEn", "You are describing your evening.")
            .put("contextLines", JSONArray().put(JSONObject().put("speaker", "AI").put("textEn", "What happened?"))).toString())
    }

    private fun scopedIdentity(account: String, chapter: String, sentence: String): String {
        val input = JSONArray(listOf("scene-response-task:v1", account, chapter, sentence)).toString()
        return "scene-" + MessageDigest.getInstance("SHA-256").digest(input.toByteArray(Charsets.UTF_8)).joinToString("") { "%02x".format(it) }
    }

    private fun repository(context: Context, runtime: SessionRuntime, transport: HttpTransport) = AndroidSceneResponseRepository(
        context, transport, runtime,
        object : ReadSpeakAudioCapture { override fun start() = false; override fun finish(): CapturedReadSpeakAudio? = null; override fun cancel() = Unit },
    )

    private fun fixture(block: suspend (Context, String, SessionRuntime, List<FixedLearningChapter>) -> Unit) = runBlocking {
        val context = ApplicationProvider.getApplicationContext<Context>()
        val account = "scene-identity-${UUID.randomUUID()}"
        val runtime = SessionRuntime().apply { update("isolated-not-a-real-session", account) }
        val chapters = (1..2).map { number -> FixedLearningChapter("c$number", number, listOf(
            FixedLearningSentence("s1", "I wrote a diary entry in chapter $number.", "我写了一篇日记。", true),
            FixedLearningSentence("s2", "I felt more confident in chapter $number.", "我更有信心了。", true))) }
        FormationDatabase(context).use { helper ->
            chapters.forEach { chapter ->
                helper.writableDatabase.execSQL("insert into chapters values (?, 'isolated-flow', ?, ?, 'NOT_STARTED')", arrayOf<Any>(account, chapter.chapterId, chapter.chapterNumber - 1))
                chapter.sentences.forEachIndexed { index, sentence ->
                    helper.writableDatabase.execSQL("insert into fixed_sentences(account_id,chapter_id,unit_id,sentence_order,text_zh,text_en,role) values (?, ?, ?, ?, ?, ?, 'FOCUS')",
                        arrayOf<Any>(account, chapter.chapterId, sentence.sentenceId, index, sentence.textZh, sentence.textEn))
                }
            }
        }
        try { block(context, account, runtime, chapters) }
        finally { FormationDatabase(context).use { helper ->
            listOf("scene_response_tasks", "fixed_sentences", "chapters").forEach { helper.writableDatabase.delete(it, "account_id=?", arrayOf(account)) }
        } }
    }
}
